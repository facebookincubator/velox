// Pins the '#'-before-'?' split: a '?' inside the fragment belongs to the
// fragment and never introduces a query.
TEST_F(ParseUrlTest, questionMarkInFragment) {
  const auto url = "http://h/p#f?g";
  EXPECT_EQ(std::nullopt, parseUrl(url, "QUERY"));
  EXPECT_EQ("f?g", parseUrl(url, "REF"));
  EXPECT_EQ("/p", parseUrl(url, "FILE"));
  EXPECT_EQ("/p", parseUrl(url, "PATH"));
  EXPECT_EQ("h", parseUrl(url, "HOST"));
  // The '?' inside the fragment also stays out of the FILE, and a query
  // key finds nothing.
  EXPECT_EQ(
      std::nullopt,
      evaluateOnce<std::string>(
          "parse_url(c0, 'QUERY', 'f')", std::optional<std::string>(url)));
}

// Pins that the key is a regex fragment, not a literal: no escaping.
TEST_F(ParseUrlTest, regexMetacharacterKey) {
  // '.' matches any character, so 'a.b' hits 'aXb=1'.
  EXPECT_EQ("1", parseUrlQuery("http://h/p?aXb=1", "a.b"));
  EXPECT_EQ(std::nullopt, parseUrlQuery("http://h/p?ab=1", "a.b"));
  // The '=' after the key is a literal, so 'b*' matching empty still
  // leaves no '=' to match: 'ab*' does not hit a bare 'a'.
  EXPECT_EQ(std::nullopt, parseUrlQuery("http://h/p?a", "ab*"));
}

// Pins IPv6 literal shapes beyond '::1': the unspecified address,
// embedded IPv4, scope ids, full-width groups, and the malformed forms.
TEST_F(ParseUrlTest, ipv6LiteralShapes) {
  const auto host = [&](const std::string& url) {
    return evaluateOnce<std::string>(
        "parse_url(c0, 'HOST')", std::optional<std::string>(url));
  };
  const auto authority = [&](const std::string& url) {
    return evaluateOnce<std::string>(
        "parse_url(c0, 'AUTHORITY')", std::optional<std::string>(url));
  };

  // Legal shapes.
  EXPECT_EQ("[::]", host("http://[::]/p"));
  EXPECT_EQ("[::ffff:1.2.3.4]", host("http://[::ffff:1.2.3.4]/p"));
  EXPECT_EQ("[1:2:3:4:5:6:7:8]", host("http://[1:2:3:4:5:6:7:8]/p"));
  // A scope id is alphanumeric only and must be non-empty; '%' is a mask
  // member in the authority, not an escape.
  EXPECT_EQ("[fe80::1%eth0]", host("http://[fe80::1%eth0]/p"));
  EXPECT_EQ("[fe80::1%eth0]:80", authority("http://[fe80::1%eth0]:80/p"));

  // Malformed shapes yield a null host. Unlike a non-IPv6 authority, a
  // malformed IPv6 literal fails the whole authority, so AUTHORITY is
  // null too.
  EXPECT_EQ(std::nullopt, host("http://[fe80::1%]/p"));
  EXPECT_EQ(std::nullopt, host("http://[fe80::1%e!h0]/p"));
  EXPECT_EQ(std::nullopt, host("http://[1:2:3:4:5:6:7:8:9]/p"));
  EXPECT_EQ(std::nullopt, host("http://[12345::]/p"));
  EXPECT_EQ(std::nullopt, host("http://[1::2::3]/p"));
  EXPECT_EQ(std::nullopt, host("http://[:1]/p"));
  EXPECT_EQ(std::nullopt, authority("http://[1::2::3]/p"));
}

// Pins that the host keeps its original casing (java.net.URI does not
