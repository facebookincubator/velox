// Exercises parse_url with components long enough to span AVX2 chunks and
// a stopper at index 40, inside the second chunk (bytes 32..63). All
// expectations verified against Spark 3.5.1.
TEST_F(ParseUrlTest, parseUrlLongComponents) {
  const auto repeat = [](int count, char c) { return std::string(count, c); };
  const auto repeatStr = [](std::string_view unit, int count) {
    std::string out;
    for (int i = 0; i < count; ++i) {
      out += unit;
    }
    return out;
  };

  // A 69-character valid hostname crosses two chunks with no stopper.
  const auto longHost = repeatStr("aaaa.", 13) + "aaaa";
  const auto longHostUrl = "http://" + longHost + "/p";
  EXPECT_EQ(longHost, parseUrl(longHostUrl, "HOST"));
  EXPECT_EQ(longHost, parseUrl(longHostUrl, "AUTHORITY"));
  EXPECT_EQ("http", parseUrl(longHostUrl, "PROTOCOL"));

  // A space at index 40 of the host fails every authority form, so the
  // whole URL is invalid and every part is null.
  const auto spaceInHostUrl =
      "http://" + repeat(40, 'a') + " " + repeat(28, 'b') + "/p";
  EXPECT_EQ(std::nullopt, parseUrl(spaceInHostUrl, "HOST"));
  EXPECT_EQ(std::nullopt, parseUrl(spaceInHostUrl, "AUTHORITY"));
  EXPECT_EQ(std::nullopt, parseUrl(spaceInHostUrl, "PATH"));

  // A malformed escape pair at index 40 invalidates the path.
  const auto badEscapePathUrl =
      "http://h/" + repeat(40, 'p') + "%x" + repeat(27, 'p');
  EXPECT_EQ(std::nullopt, parseUrl(badEscapePathUrl, "PATH"));

  // A CJK character at index 40 of the path and the query is accepted
  // and preserved byte-for-byte.
  const auto cjkPathUrl =
      "http://h/" + repeat(40, 'p') + "中" + repeat(27, 'p');
  EXPECT_EQ(
      "/" + repeat(40, 'p') + "中" + repeat(27, 'p'),
      parseUrl(cjkPathUrl, "PATH"));
  const auto cjkQueryUrl = "http://h/p?" + repeat(40, 'k') + "=美&x=1";
  EXPECT_EQ(repeat(40, 'k') + "=美&x=1", parseUrl(cjkQueryUrl, "QUERY"));
}

