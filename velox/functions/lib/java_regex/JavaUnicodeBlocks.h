inline constexpr size_t kJavaUnicodeBlockCount =
    sizeof(kJavaUnicodeBlocks) / sizeof(kJavaUnicodeBlocks[0]);

// Resolves a normalized Java block name to its code-point range. Tries an exact
// match first, then falls back to the first block whose name starts with the
// query (covers Java aliases such as "greek" -> "Greek and Coptic"). Returns
// std::nullopt when nothing matches, so callers leave the property untouched
// and RE2 rejects it (graceful Spark fallback).
inline std::optional<std::pair<uint32_t, uint32_t>> lookupJavaUnicodeBlock(
    const std::string& normalized) {
  size_t lo = 0, hi = kJavaUnicodeBlockCount;
  while (lo < hi) {
    const size_t mid = (lo + hi) / 2;
    const int cmp = normalized.compare(kJavaUnicodeBlocks[mid].name);
    if (cmp == 0) {
      return std::make_pair(
          kJavaUnicodeBlocks[mid].lo, kJavaUnicodeBlocks[mid].hi);
    }
    if (cmp < 0) {
      hi = mid;
    } else {
      lo = mid + 1;
    }
  }
  // Prefix fallback: 'lo' is the first name >= query; accept it if it starts
  // with the query string.
  if (lo < kJavaUnicodeBlockCount) {
    const std::string cand = kJavaUnicodeBlocks[lo].name;
    if (cand.size() >= normalized.size() &&
        cand.compare(0, normalized.size(), normalized) == 0) {
      return std::make_pair(
          kJavaUnicodeBlocks[lo].lo, kJavaUnicodeBlocks[lo].hi);
    }
  }
  return std::nullopt;
}

