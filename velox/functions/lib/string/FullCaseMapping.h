/// Which uppercase mapping upperUnicode applies.
enum class CaseMapping {
  /// One-to-one mapping, from utf8proc_toupper.
  kSimple,
  /// Unicode full uppercase mapping, where one code point can become several.
  kFullUpper,
  /// Unicode full titlecase mapping, used for the first letter of a word.
  kFullTitle,
};

/// The uppercase and titlecase forms of one code point. Unused trailing slots
/// are 0.
struct FullCaseMapping {
  int32_t codePoint;
  std::array<int32_t, 3> upper;
  std::array<int32_t, 3> title;
};

