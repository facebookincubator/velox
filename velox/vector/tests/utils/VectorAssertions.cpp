// static
void VectorAssertions::equal(
    const VectorPtr& expected,
    const VectorPtr& actual) {
  ASSERT_EQ(expected->size(), actual->size());
  ASSERT_TRUE(expected->type()->equivalent(*actual->type()))
      << "Expected " << expected->type()->toString() << ", but got "
      << actual->type()->toString();
  for (auto i = 0; i < expected->size(); i++) {
    ASSERT_TRUE(expected->equalValueAt(actual.get(), i, i))
        << "at " << i << ": expected " << expected->toString(i) << ", but got "
        << actual->toString(i);
  }
}

// static
void VectorAssertions::equal(
    const VectorPtr& expected,
    const VectorPtr& actual,
    const SelectivityVector& rows) {
  ASSERT_LE(rows.end(), actual->size())
      << "Vectors should at least have the required amount of rows that need "
         "to be verified.";
  ASSERT_TRUE(expected->type()->equivalent(*actual->type()))
      << "Expected " << expected->type()->toString() << ", but got "
      << actual->type()->toString();
  rows.applyToSelected([&](vector_size_t i) {
    ASSERT_TRUE(expected->equalValueAt(actual.get(), i, i))
        << "at " << i << ": expected " << expected->toString(i) << ", but got "
        << actual->toString(i);
  });
}

// static
std::vector<std::vector<Variant>> VectorAssertions::toVariantRows(
    const RowVectorPtr& vector) {
  const auto size = vector->size();
  const auto numColumns = vector->childrenSize();

  // variantAt() casts to SimpleVector, so load lazy columns first.
  std::vector<VectorPtr> columns(numColumns);
  for (size_t i = 0; i < numColumns; ++i) {
    columns[i] = BaseVector::loadedVectorShared(vector->childAt(i));
  }

  std::vector<std::vector<Variant>> rows;
  rows.reserve(size);
  for (vector_size_t i = 0; i < size; ++i) {
    std::vector<Variant> row;
    row.reserve(numColumns);
    for (size_t j = 0; j < numColumns; ++j) {
      row.push_back(columns[j]->variantAt(i));
    }
    rows.push_back(std::move(row));
  }
  return rows;
}

// static
std::multiset<std::vector<Variant>> VectorAssertions::toMultiset(
    const std::vector<RowVectorPtr>& vectors) {
  std::multiset<std::vector<Variant>> rows;
  for (const auto& vector : vectors) {
    for (auto& row : toVariantRows(vector)) {
      rows.insert(std::move(row));
    }
  }
  return rows;
}

// static
void VectorAssertions::equalOrdered(
    const std::vector<std::vector<Variant>>& expected,
    const TypePtr& expectedType,
    const std::vector<RowVectorPtr>& actual,
    bool epsilon) {
  ASSERT_TRUE(equalTypes(expectedType, actual));

  std::vector<std::vector<Variant>> actualRows;
  for (const auto& vector : actual) {
    auto rows = toVariantRows(vector);
    actualRows.insert(
        actualRows.end(),
        std::make_move_iterator(rows.begin()),
        std::make_move_iterator(rows.end()));
  }

  ASSERT_EQ(expected.size(), actualRows.size()) << "Row counts differ";

  for (size_t i = 0; i < expected.size(); ++i) {
    const bool equal = epsilon ? equalsWithEpsilon(expected[i], actualRows[i])
                               : expected[i] == actualRows[i];
    ASSERT_TRUE(equal) << "Rows differ at position " << i << ":\n  expected: "
                       << toString(expected[i], expectedType)
                       << "\n  actual:   "
                       << toString(actualRows[i], expectedType);
  }
}

// static
bool VectorAssertions::equalMultisets(
    const std::vector<RowVectorPtr>& expected,
    const std::vector<RowVectorPtr>& actual) {
  if (expected.empty()) {
    return actual.empty() || equalMultisets({}, actual.front()->type(), actual);
  }
  return equalMultisets(toMultiset(expected), expected.front()->type(), actual);
}

// static
bool VectorAssertions::equalMultisets(
    const std::multiset<std::vector<Variant>>& expected,
    const TypePtr& expectedType,
    const std::vector<RowVectorPtr>& actual) {
  return equalTypes(expectedType, actual) &&
      equalMultisets(expected, toMultiset(actual), expectedType);
}

// static
bool VectorAssertions::equalMultisets(
    const std::multiset<std::vector<Variant>>& expected,
    const std::multiset<std::vector<Variant>>& actual,
    const TypePtr& type) {
  if (expected.empty() != actual.empty()) {
    ADD_FAILURE() << generateUserFriendlyDiff(expected, actual, type);
    return false;
  }

  if (expected.empty()) {
    return true;
  }

  if (auto mismatch = compareRows(expected, actual, type)) {
    ADD_FAILURE() << *mismatch;
    return false;
  }
  return true;
}

// static
void VectorAssertions::equalOrderedBy(
    const std::vector<std::vector<Variant>>& expected,
    const RowTypePtr& expectedType,
    const std::vector<RowVectorPtr>& actual,
    const std::vector<uint32_t>& sortingKeys) {
  ASSERT_TRUE(equalTypes(expectedType, actual));

  std::vector<OrderedPartition> expectedPartitions;
  appendOrderedPartitions(expected, sortingKeys, expectedPartitions);

  std::vector<OrderedPartition> actualPartitions;
  for (const auto& vector : actual) {
    appendOrderedPartitions(
        toVariantRows(vector), sortingKeys, actualPartitions);
  }

  size_t i = 0;
  while (i < expectedPartitions.size() && i < actualPartitions.size() &&
         compareOrderedPartitions(
             expectedPartitions[i], actualPartitions[i], expectedType)) {
    ++i;
  }

  const auto keyType = keysType(expectedType, sortingKeys);
  if (i == expectedPartitions.size()) {
    if (i < actualPartitions.size()) {
      ADD_FAILURE() << "Got extra rows: keys: "
                    << toString(actualPartitions[i].first, keyType);
    }
    return;
  }

  if (i == actualPartitions.size()) {
    ADD_FAILURE() << "Missing rows: keys: "
                  << toString(expectedPartitions[i].first, keyType);
    return;
  }

  const auto& expectedPartition = expectedPartitions[i];
  const auto& actualPartition = actualPartitions[i];
  if (expectedPartition.first != actualPartition.first) {
    ADD_FAILURE() << "Expected keys: "
                  << toString(expectedPartition.first, keyType)
                  << ", actual: " << toString(actualPartition.first, keyType);
    return;
  }

  ADD_FAILURE() << "Keys: " << toString(expectedPartition.first, keyType) << " "
                << compareRows(
                       expectedPartition.second,
                       actualPartition.second,
                       expectedType)
                       .value_or("");
}

